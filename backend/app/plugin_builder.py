import io
import re
import zipfile
from xml.sax.saxutils import escape as xml_escape


def _safe_identifier(value: str, fallback: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_]", "", value) or fallback
    if cleaned[0].isdigit():
        cleaned = "Plugin" + cleaned
    return cleaned


def build_paper_plugin(name: str, package_name: str, version: str, minecraft_version: str) -> bytes:
    """Create a source ZIP for a minimal Paper plugin (does not compile it)."""
    safe_name = _safe_identifier(name, "StarterPlugin")
    parts = package_name.split(".")
    if len(parts) < 2 or any(not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", part) for part in parts):
        raise ValueError("Package must look like com.example.plugin")
    if not re.fullmatch(r"[0-9]+(?:\.[0-9]+){1,2}", version):
        raise ValueError("Version must use numeric format, e.g. 1.0.0")
    if not re.fullmatch(r"[0-9]+\.[0-9]+(?:\.[0-9]+)?", minecraft_version):
        raise ValueError("Minecraft version must look like 1.21.4")
    package_path = "/".join(parts)
    api_version = ".".join(minecraft_version.split(".")[:2])
    pom = f'''<?xml version="1.0" encoding="UTF-8"?>
<project xmlns="http://maven.apache.org/POM/4.0.0" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://maven.apache.org/POM/4.0.0 https://maven.apache.org/xsd/maven-4.0.0.xsd">
  <modelVersion>4.0.0</modelVersion>
  <groupId>{xml_escape(package_name)}</groupId><artifactId>{xml_escape(safe_name.lower())}</artifactId><version>{xml_escape(version)}</version>
  <properties><maven.compiler.release>21</maven.compiler.release><project.build.sourceEncoding>UTF-8</project.build.sourceEncoding></properties>
  <repositories><repository><id>papermc</id><url>https://repo.papermc.io/repository/maven-public/</url></repository></repositories>
  <dependencies><dependency><groupId>io.papermc.paper</groupId><artifactId>paper-api</artifactId><version>{xml_escape(minecraft_version)}-R0.1-SNAPSHOT</version><scope>provided</scope></dependency></dependencies>
  <build><plugins><plugin><groupId>org.apache.maven.plugins</groupId><artifactId>maven-compiler-plugin</artifactId><version>3.13.0</version></plugin></plugins></build>
</project>
'''
    java = f'''package {package_name};

import org.bukkit.plugin.java.JavaPlugin;

public final class {safe_name} extends JavaPlugin {{
    @Override public void onEnable() {{ getLogger().info("{safe_name} enabled!"); }}
    @Override public void onDisable() {{ getLogger().info("{safe_name} disabled."); }}
}}
'''
    descriptor = f"""name: {safe_name}
version: {version}
main: {package_name}.{safe_name}
api-version: '{api_version}'
description: A starter Paper plugin generated by Your AI
"""
    readme = ("# Generated Paper plugin starter\n\nRequirements: JDK 21 and Maven. "
              "Run mvn package in this folder; the JAR is written to target/.\n\n"
              "This ZIP contains source files only; it does not compile or install "
              "the plugin. Test on a separate server before using it live.\n")
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as archive:
        root = safe_name
        archive.writestr(f"{root}/pom.xml", pom)
        archive.writestr(f"{root}/README.md", readme)
        archive.writestr(f"{root}/src/main/java/{package_path}/{safe_name}.java", java)
        archive.writestr(f"{root}/src/main/resources/plugin.yml", descriptor)
    return output.getvalue()
